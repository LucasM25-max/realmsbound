export function numWidth(str) { let w = 0; for (const ch of str) w += (NUM[ch] ? NUM[ch][0].length : 3) + 1; return w - 1; }
// col: [face, highlight(top row)], drawn at native (X,Y) top-left; align l|c|r
export function num(c, str, X, Y, col = ['#fbe9c4', '#ffffff'], align = 'l', { outline = '#140b0c', scale = 1, shadow = true } = {}) {
  const w = numWidth(str) * scale; if (align === 'c') X -= Math.floor(w / 2); else if (align === 'r') X -= w;
  X = Math.round(X); Y = Math.round(Y);
  const pts = []; let px = X;
  for (const ch of str) {
    const g = NUM[ch];
    if (g) g.forEach((row, j) => [...row].forEach((v, i) => { if (v === '1') for (let b = 0; b < scale; b++) for (let a = 0; a < scale; a++) pts.push([px + i * scale + a, Y + j * scale + b, j, b]); }));
    px += ((g ? g[0].length : 3) + 1) * scale;
  }
  if (outline) {
    c.fillStyle = outline;
    for (const [x, y] of pts) { c.fillRect(x - 1, y, 3, 1); c.fillRect(x, y - 1, 1, 3); if (shadow) c.fillRect(x, y + 2, 1, 1); }
  }
  for (const [x, y, j, b] of pts) { c.fillStyle = (j === 0 && b === 0) ? col[1] : (col[2] && j >= 5) ? col[2] : col[0]; c.fillRect(x, y, 1, 1); }
  return w;
}
